"use client";

import { useMemo, useState } from "react";
import {
  LineChart, Line, XAxis, YAxis, CartesianGrid, Tooltip as RTooltip, ResponsiveContainer, Legend,
} from "recharts";
import { PageHeader, Panel, PanelHeader, Button, Slider, Select, SimulatedBanner, Badge } from "@/components/ui";
import { LR_PRESETS, simulateTraining, summarize, type TrainConfig } from "@/lib/sim/training";
import { useInterval } from "@/hooks";
import { useToast } from "@/components/toast";

export default function TrainingObservatoryPage() {
  const toast = useToast();
  const [cfg, setCfg] = useState<TrainConfig>({ lr: 0.0005, epochs: 30, batchSize: 32, optimizer: "AdamW" });
  const [epoch, setEpoch] = useState(0);
  const [running, setRunning] = useState(false);

  const curve = useMemo(() => simulateTraining(cfg), [cfg]);
  const shown = useMemo(() => curve.slice(0, epoch), [curve, epoch]);
  const stats = useMemo(() => (epoch > 0 ? summarize(curve, epoch) : null), [curve, epoch]);

  useInterval(() => {
    setEpoch((e) => {
      if (e + 1 >= cfg.epochs) {
        setRunning(false);
        toast("Simulated training run complete", "good");
        return cfg.epochs;
      }
      return e + 1;
    });
  }, running ? 220 : null);

  const update = (patch: Partial<TrainConfig>) => {
    setCfg((c) => ({ ...c, ...patch }));
    setEpoch(0);
    setRunning(false);
  };

  const totalBatches = Math.ceil(50000 / cfg.batchSize);
  const progress = (epoch / cfg.epochs) * 100;

  return (
    <div className="mx-auto max-w-7xl space-y-5">
      <PageHeader
        title="Training Observatory"
        description="Watch simulated training dynamics respond to hyperparameters. Curves are generated by deterministic functions — no real training occurs."
        actions={
          <>
            <Button variant={running ? "outline" : "primary"} onClick={() => { if (epoch >= cfg.epochs) setEpoch(0); setRunning((r) => !r); }}>
              {running ? "Pause" : epoch === 0 ? "Start Training" : "Resume"}
            </Button>
            <Button onClick={() => setEpoch((e) => Math.min(e + 1, cfg.epochs))} disabled={epoch >= cfg.epochs}>Step Epoch</Button>
            <Button variant="ghost" onClick={() => { setRunning(false); setEpoch(0); toast("Run reset", "info"); }}>Reset</Button>
          </>
        }
      />
      <SimulatedBanner>Educational simulation — curves are synthesized from deterministic formulas parameterized by your configuration, not measured from a real model.</SimulatedBanner>

      <div className="grid gap-4 xl:grid-cols-[300px_1fr]">
        <div className="space-y-4">
          <Panel>
            <PanelHeader title="Training Configuration" sub="Changing config resets the run" />
            <div className="space-y-4 p-4">
              <Select label="Learning rate" value={String(cfg.lr)} options={LR_PRESETS} onChange={(v) => update({ lr: Number(v) })} />
              <Slider label="Epochs" value={cfg.epochs} min={10} max={80} onChange={(v) => update({ epochs: v })} />
              <Select
                label="Batch size"
                value={String(cfg.batchSize)}
                options={[
                  { value: "16", label: "16 · noisy gradients" },
                  { value: "32", label: "32 · balanced" },
                  { value: "64", label: "64 · stable, slower steps" },
                  { value: "128", label: "128 · large batch" },
                ]}
                onChange={(v) => update({ batchSize: Number(v) })}
              />
              <Select
                label="Optimizer"
                value={cfg.optimizer}
                options={[
                  { value: "AdamW", label: "AdamW" },
                  { value: "Adam", label: "Adam" },
                  { value: "SGD", label: "SGD · constant LR" },
                ]}
                onChange={(v) => update({ optimizer: v as TrainConfig["optimizer"] })}
              />
            </div>
          </Panel>

          <Panel>
            <PanelHeader title="Run Status" sub={stats ? `Epoch ${stats.epochsDone} of ${cfg.epochs}` : "Not started"} />
            <div className="space-y-3 p-4 text-xs">
              <div className="h-1.5 overflow-hidden rounded-full bg-line">
                <div className="h-full rounded-full bg-accent transition-all duration-200" style={{ width: `${progress}%` }} />
              </div>
              {stats ? (
                <>
                  <Row k="Train loss" v={stats.last.trainLoss.toFixed(4)} />
                  <Row k="Validation loss" v={stats.last.valLoss.toFixed(4)} />
                  <Row k="Train accuracy" v={`${(stats.last.trainAcc * 100).toFixed(2)}%`} />
                  <Row k="Validation accuracy" v={`${(stats.last.valAcc * 100).toFixed(2)}%`} />
                  <Row k="Current LR" v={stats.last.lr.toExponential(2)} />
                  <Row k="Batches / epoch" v={String(totalBatches)} />
                  <Row k="Best val loss" v={`${stats.best.valLoss.toFixed(4)} @ epoch ${stats.best.epoch}`} />
                  <div className="pt-1">
                    {stats.overfitting ? (
                      <Badge tone="warn">Overfitting signal: validation loss diverging from best</Badge>
                    ) : (
                      <Badge tone="good">Validation loss at or near best</Badge>
                    )}
                  </div>
                </>
              ) : (
                <p className="text-mute">Press Start Training to begin the simulated run.</p>
              )}
            </div>
          </Panel>
        </div>

        <div className="space-y-4">
          <Panel>
            <PanelHeader title="Loss Curves" sub="Training vs validation" />
            <div className="h-72 p-4">
              <ResponsiveContainer width="100%" height="100%">
                <LineChart data={shown}>
                  <CartesianGrid stroke="#1b2633" strokeDasharray="3 3" />
                  <XAxis dataKey="epoch" tick={{ fill: "#8793a5", fontSize: 10 }} />
                  <YAxis tick={{ fill: "#8793a5", fontSize: 10 }} />
                  <RTooltip contentStyle={{ background: "#121823", border: "1px solid #1b2633", fontSize: 12 }} />
                  <Legend wrapperStyle={{ fontSize: 11, color: "#8793a5" }} />
                  <Line type="monotone" name="Training loss" dataKey="trainLoss" stroke="#00d9ff" dot={false} strokeWidth={2} isAnimationActive={false} />
                  <Line type="monotone" name="Validation loss" dataKey="valLoss" stroke="#ff647c" dot={false} strokeWidth={2} strokeDasharray="5 3" isAnimationActive={false} />
                </LineChart>
              </ResponsiveContainer>
            </div>
          </Panel>

          <Panel>
            <PanelHeader title="Accuracy Curves" sub="Training vs validation accuracy" />
            <div className="h-72 p-4">
              <ResponsiveContainer width="100%" height="100%">
                <LineChart data={shown}>
                  <CartesianGrid stroke="#1b2633" strokeDasharray="3 3" />
                  <XAxis dataKey="epoch" tick={{ fill: "#8793a5", fontSize: 10 }} />
                  <YAxis domain={[0, 1]} tick={{ fill: "#8793a5", fontSize: 10 }} tickFormatter={(v: number) => `${(v * 100).toFixed(0)}%`} />
                  <RTooltip contentStyle={{ background: "#121823", border: "1px solid #1b2633", fontSize: 12 }} />
                  <Legend wrapperStyle={{ fontSize: 11, color: "#8793a5" }} />
                  <Line type="monotone" name="Training acc" dataKey="trainAcc" stroke="#38d996" dot={false} strokeWidth={2} isAnimationActive={false} />
                  <Line type="monotone" name="Validation acc" dataKey="valAcc" stroke="#a78bfa" dot={false} strokeWidth={2} strokeDasharray="5 3" isAnimationActive={false} />
                </LineChart>
              </ResponsiveContainer>
            </div>
          </Panel>
        </div>
      </div>
    </div>
  );
}

function Row({ k, v }: { k: string; v: string }) {
  return (
    <div className="flex items-center justify-between border-b border-line/60 pb-1.5">
      <span className="text-mute">{k}</span>
      <span className="font-mono text-ink">{v}</span>
    </div>
  );
}
