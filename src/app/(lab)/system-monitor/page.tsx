"use client";

import { useMemo, useState } from "react";
import {
  AreaChart, Area, XAxis, YAxis, CartesianGrid, ResponsiveContainer, Tooltip as RTooltip,
} from "recharts";
import { PageHeader, Panel, PanelHeader, SimulatedBanner, Stat, Badge, Button, EmptyState } from "@/components/ui";
import { METRICS, eventFor, tickMetrics, type MetricSample, type Sev } from "@/lib/sim/metrics";
import { useInterval, useLocalStorage } from "@/hooks";

const SEV_TONE = { info: "accent", warn: "warn", good: "good", bad: "bad" } as const;

export default function SystemMonitorPage() {
  const [tick, setTick] = useState(0);
  const [running, setRunning] = useState(true);
  const [history, setHistory] = useState<Record<string, MetricSample[]>>({});
  const [events, setEvents] = useState<Array<{ id: number; t: number; sev: Sev; msg: string }>>([]);
  const [logUptime] = useLocalStorage("nx-uptime-start", 0);

  const uptime = useMemo(() => {
    const secs = logUptime ? (Date.now() - logUptime) / 1000 : 3600 * 2;
    const h = Math.floor(secs / 3600), m = Math.floor((secs % 3600) / 60);
    return `${h}h ${m}m`;
  }, [logUptime]);

  useInterval(() => {
    setTick((t) => {
      const nt = t + 1;
      setHistory((h) => tickMetrics(h, nt));
      const ev = eventFor(nt);
      if (ev) setEvents((e) => [{ id: nt, t: nt, ...ev }, ...e].slice(0, 12));
      return nt;
    });
  }, running ? 1400 : null);

  const activeTasks = 3 + ((tick * 7) % 5);
  const chartData = useMemo(() => {
    const keys = METRICS.map((m) => m.id);
    const len = Math.max(...keys.map((k) => history[k]?.length ?? 0), 0);
    return Array.from({ length: len }, (_, i) => {
      const row: Record<string, number> = { t: i };
      keys.forEach((k) => (row[k] = history[k]?.[i]?.v ?? 0));
      return row;
    });
  }, [history]);

  const val = (id: string) => history[id]?.[history[id].length - 1]?.v;

  return (
    <div className="mx-auto max-w-7xl space-y-5">
      <PageHeader
        title="System Monitor"
        description="Simulated infrastructure telemetry rendered in the browser. None of these values are measured from real hardware."
        actions={
          <>
            <Button variant={running ? "outline" : "primary"} onClick={() => setRunning((r) => !r)}>{running ? "Pause Feed" : "Resume Feed"}</Button>
            <Button variant="ghost" onClick={() => { setHistory({}); setEvents([]); setTick(0); }}>Clear History</Button>
          </>
        }
      />
      <SimulatedBanner>All metrics are generated by a deterministic browser-side simulator for demonstration purposes.</SimulatedBanner>

      <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <Stat label="System Status" value="Operational" hint="simulated health" />
        <Stat label="System Uptime" value={uptime} hint="session-tracked" />
        <Stat label="Active Tasks" value={activeTasks} hint="simulated scheduler" />
        <Stat label="Samples Collected" value={tick} hint="metric feed ticks" />
      </div>

      <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
        {METRICS.map((m) => {
          const v = val(m.id);
          const prev = history[m.id]?.[history[m.id].length - 2]?.v;
          const delta = v !== undefined && prev !== undefined ? v - prev : 0;
          return (
            <div key={m.id} className="rounded-xl border border-line bg-panel p-4">
              <div className="flex items-center justify-between">
                <span className="text-xs text-mute">{m.label}</span>
                <span className={`font-mono text-[10px] ${delta > 0.5 ? "text-good" : delta < -0.5 ? "text-bad" : "text-mute"}`}>
                  {delta !== 0 ? `${delta > 0 ? "▲" : "▼"} ${Math.abs(delta).toFixed(m.decimals)}` : "—"}
                </span>
              </div>
              <div className="mt-1 font-mono text-2xl text-ink">
                {v !== undefined ? `${v.toFixed(m.decimals)}${m.unit === "%" ? "%" : ` ${m.unit}`}` : "—"}
              </div>
              <svg viewBox="0 0 100 24" preserveAspectRatio="none" className="mt-2 h-6 w-full">
                {history[m.id]?.length > 1 && (() => {
                  const pts = history[m.id];
                  const min = Math.min(...pts.map((p) => p.v)), max = Math.max(...pts.map((p) => p.v));
                  const range = max - min || 1;
                  const d = pts.map((p, i) => `${i === 0 ? "M" : "L"}${(i / (pts.length - 1)) * 100},${22 - ((p.v - min) / range) * 20}`).join(" ");
                  return <path d={d} fill="none" stroke="#00d9ff" strokeWidth={1.4} opacity={0.85} />;
                })()}
              </svg>
            </div>
          );
        })}
      </div>

      <div className="grid gap-4 xl:grid-cols-[1fr_340px]">
        <Panel>
          <PanelHeader title="Historical Charts" sub="CPU · GPU · latency (simulated feed)" />
          <div className="h-64 p-4">
            {chartData.length === 0 ? (
              <EmptyState title="Waiting for telemetry" hint="The feed is populating — keep this page open." />
            ) : (
              <ResponsiveContainer width="100%" height="100%">
                <AreaChart data={chartData}>
                  <defs>
                    <linearGradient id="g1" x1="0" y1="0" x2="0" y2="1">
                      <stop offset="0%" stopColor="#00d9ff" stopOpacity={0.3} />
                      <stop offset="100%" stopColor="#00d9ff" stopOpacity={0} />
                    </linearGradient>
                    <linearGradient id="g2" x1="0" y1="0" x2="0" y2="1">
                      <stop offset="0%" stopColor="#7667ff" stopOpacity={0.3} />
                      <stop offset="100%" stopColor="#7667ff" stopOpacity={0} />
                    </linearGradient>
                  </defs>
                  <CartesianGrid stroke="#1b2633" strokeDasharray="3 3" />
                  <XAxis dataKey="t" tick={{ fill: "#51607a", fontSize: 9 }} />
                  <YAxis tick={{ fill: "#51607a", fontSize: 9 }} />
                  <RTooltip contentStyle={{ background: "#121823", border: "1px solid #1b2633", fontSize: 12 }} />
                  <Area name="GPU %" type="monotone" dataKey="gpu" stroke="#7667ff" fill="url(#g2)" strokeWidth={1.6} isAnimationActive={false} />
                  <Area name="CPU %" type="monotone" dataKey="cpu" stroke="#00d9ff" fill="url(#g1)" strokeWidth={1.6} isAnimationActive={false} />
                  <Area name="Latency ms ÷ 10" type="monotone" dataKey="latency" stroke="#38d996" fill="none" strokeWidth={1.2} isAnimationActive={false} />
                </AreaChart>
              </ResponsiveContainer>
            )}
          </div>
        </Panel>

        <Panel>
          <PanelHeader title="Event Log" sub="Simulated system events" right={<Badge tone="neutral">{events.length}</Badge>} />
          <div className="max-h-64 overflow-y-auto p-3">
            {events.length === 0 ? (
              <EmptyState title="No events" hint="Events appear as the simulated feed runs." />
            ) : (
              <ul className="space-y-2">
                {events.map((e) => (
                  <li key={e.id} className="flex items-start gap-2 rounded-lg border border-line bg-elevated/50 px-2.5 py-2 text-xs">
                    <Badge tone={SEV_TONE[e.sev]} className="mt-px">{e.sev}</Badge>
                    <span className="flex-1 text-mute">{e.msg}</span>
                    <span className="font-mono text-[10px] text-mute/60">t{e.t}</span>
                  </li>
                ))}
              </ul>
            )}
          </div>
        </Panel>
      </div>
    </div>
  );
}
